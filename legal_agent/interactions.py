"""Presentation components; animation state follows actual application work."""
from contextlib import contextmanager
from pathlib import Path
import html
import streamlit.components.v1 as components

_export = components.declare_component("juriscloud_export", path=str(
    Path(__file__).resolve().parents[1] / "assets/exporter"))


_copy = components.declare_component("juriscloud_copy", path=str(
    Path(__file__).resolve().parents[1] / "assets/copier"))


def copy_answer(text, language, key):
    """Clipboard writes happen only inside the browser's deliberate button click."""
    return _copy(text=text, english=language == "English", key=key, default=None)


def queue_followup(session):
    """Capture accepted input before Streamlit re-renders its widgets, then clear them."""
    question=session.get("question","")
    if (session.get("_pending_followup") or not session.get("api_key") or
            not question.strip() or len(session.get("messages",[])) >= 20):
        return False
    session["_pending_followup"]={"question":question,"facts":session.get("new_facts",""),
                                  "clause":session.get("selected_clause","")}
    session["question"]=""
    session["new_facts"]=""
    session.pop("_followup_failure",None)
    return True


@contextmanager
def analysis_activity(ui, tx, reduce_motion=False):
    with ui.container(key="analysis_activity"):
        indicator = ui.empty()
        indicator.markdown(
            '<div class="thinking-cloud-panel' + (' motion-paused' if reduce_motion else '') +
            '" role="status"><span class="thinking-cloud" aria-hidden="true">💭</span>' +
            '<span>' + html.escape(tx("正在分析…")) + '</span></div>', unsafe_allow_html=True)
        try:
            with ui.status(tx("分析过程"), expanded=True) as status:
                yield status
        finally:
            # Includes errors/cancellation: never leave a breathing "working" state behind.
            indicator.empty()


def pdf_preview_url(pdf):
    """Register the generated bytes with Streamlit's session-managed media server.

    The distinct filename keeps this inline preview separate from the attachment
    created by the existing PDF download button. No files are written to disk.
    This adapter targets the Streamlit version pinned in requirements.txt.
    """
    from streamlit import runtime, config
    if not pdf or not runtime.exists(): return None
    url=runtime.get_instance().media_file_mgr.add(pdf,"application/pdf","juriscloud.report.preview",
        file_name="review-preview.pdf",is_for_static_download=False)
    base=config.get_option("server.baseUrlPath").strip("/")
    return "/"+base+url if base else url


def export_action(state, language, reduce_motion, pdf=None):
    return _export(state=state, english=language == "English", reduce_motion=reduce_motion,
        pdf_url=pdf_preview_url(pdf) if state == "ready" else None,
        key="export_action", default=None)


def consume_export_request(session, event):
    """Component values persist across reruns; consume each deliberate click once."""
    if not isinstance(event, dict) or event.get("action") != "generate":
        return False
    nonce = event.get("nonce")
    if not isinstance(nonce, str) or not nonce or len(nonce) > 100:
        return False
    if nonce == session.get("_export_nonce") or session.get("export_state") == "generating":
        return False
    session["_export_nonce"] = nonce
    session["export_state"] = "generating"
    session.pop("export_error", None)
    return True
